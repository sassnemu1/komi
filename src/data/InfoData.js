// ─── Превращает одну категорию в набор карточек для ServicesSlider ──
// Первая карточка — обзорная (заголовок + описание категории),
// остальные — её выделенные пункты (works).
export function getCategorySlides(item) {
  return [
    {
      id: item.id,
      tag: item.tag,
      title: item.title,
      desc: item.desc,
      color: item.color,
      image: item.image,
      // Обзорная карточка раскрывает в оверлее все пункты категории
      works: item.works,
    },
    ...item.works.map((work, i) => ({
      id: `${item.id}.${i + 1}`,
      tag: work.sub,
      title: work.title,
      desc: work.desc ?? work.sub,
      color: item.color,
      image: work.image ?? null,
      thumbBg: work.thumbBg ?? null,
      year: work.year ?? null,
      href: work.href ?? null,
      location: work.location ?? null,
      badge: work.badge ?? null,
      works: [],
    })),
  ];
}
